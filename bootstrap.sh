#!/bin/bash
# =============================================================================
# Agent Second Brain: точка входа установки
# =============================================================================
# Запускается из склонированного ЧИСТОГО дистрибутива, первый раз и повторно:
#
#   bash ~/projects/agent-second-brain/bootstrap.sh
#
# Полная команда первого запуска (git clone публичного репозитория и этот
# скрипт) есть в docs/install.ru.md, раздел «Одна команда запуска». Скрипт ничего не
# скачивает из интернета сам: он запускает setup.sh рядом с собой, поэтому
# версия установщика всегда совпадает с версией склонированного кода.
# =============================================================================

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

if [ "$EUID" -eq 0 ]; then
    echo "[X] Не запускайте установку от root."
    echo "    Войдите обычным пользователем по SSH: ssh user@IP_СЕРВЕРА  (docs/install.ru.md, раздел «5. Рабочий пользователь»)"
    exit 1
fi

if [ ! -f "$HERE/setup.sh" ] || [ ! -d "$HERE/src/d_brain" ]; then
    echo "[X] bootstrap.sh нужно запускать из папки склонированного дистрибутива."
    echo "    Команда первого запуска: docs/install.ru.md, раздел «Одна команда запуска»."
    exit 1
fi

exec bash "$HERE/setup.sh" "$@"
